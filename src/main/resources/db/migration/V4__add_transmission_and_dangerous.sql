-- V4 — S07: hộp số trên phiên thi + toggle tình huống nguy hiểm trên preset.
-- Idempotent: mỗi cột chỉ ALTER khi chưa có (MySQL không có ADD COLUMN IF NOT EXISTS).
-- KHÔNG sửa V1–V3.
SET @col := (SELECT COUNT(*) FROM INFORMATION_SCHEMA.COLUMNS
  WHERE TABLE_SCHEMA = DATABASE() AND TABLE_NAME = 'SH_SESSION' AND COLUMN_NAME = 'TRANSMISSION');
SET @sql := IF(@col = 0,
  'ALTER TABLE SH_SESSION ADD COLUMN TRANSMISSION VARCHAR(10) NOT NULL DEFAULT ''MANUAL''',
  'SELECT 1');
PREPARE stmt FROM @sql; EXECUTE stmt; DEALLOCATE PREPARE stmt;

SET @col := (SELECT COUNT(*) FROM INFORMATION_SCHEMA.COLUMNS
  WHERE TABLE_SCHEMA = DATABASE() AND TABLE_NAME = 'SH_PRESET' AND COLUMN_NAME = 'DANGEROUS_ENABLED');
SET @sql := IF(@col = 0,
  'ALTER TABLE SH_PRESET ADD COLUMN DANGEROUS_ENABLED TINYINT NOT NULL DEFAULT 0',
  'SELECT 1');
PREPARE stmt FROM @sql; EXECUTE stmt; DEALLOCATE PREPARE stmt;

SET @col := (SELECT COUNT(*) FROM INFORMATION_SCHEMA.COLUMNS
  WHERE TABLE_SCHEMA = DATABASE() AND TABLE_NAME = 'SH_PRESET' AND COLUMN_NAME = 'DANGEROUS_TIMEOUT_SECONDS');
SET @sql := IF(@col = 0,
  'ALTER TABLE SH_PRESET ADD COLUMN DANGEROUS_TIMEOUT_SECONDS INT NOT NULL DEFAULT 5',
  'SELECT 1');
PREPARE stmt FROM @sql; EXECUTE stmt; DEALLOCATE PREPARE stmt;

-- Lỗi tình huống nguy hiểm: không xử lý trong N giây -> trừ 10 điểm (không liệt).
-- Seed cho mọi preset chưa có lỗi này.
INSERT INTO SH_ERROR_RULE (PRESET_ID, LESSON_NO, CODE, NAME, DEDUCT_POINTS, IS_LIET, SORT_ORDER)
SELECT p.ID, 0, 'DANGEROUS', 'Không xử lý tình huống nguy hiểm', 10, 0, 99
FROM SH_PRESET p
WHERE NOT EXISTS (SELECT 1 FROM SH_ERROR_RULE e
  WHERE e.PRESET_ID = p.ID AND e.CODE = 'DANGEROUS');
